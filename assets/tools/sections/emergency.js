function calcCalories() {
  const w = parseFloat(document.getElementById("cal-w").value);
  const h = parseFloat(document.getElementById("cal-h").value);
  const age = parseFloat(document.getElementById("cal-age").value);
  const sex = document.getElementById("cal-sex").value;
  const act = parseFloat(document.getElementById("cal-act").value);
  const bmr = sex === "m" ? 10*w + 6.25*h - 5*age + 5 : 10*w + 6.25*h - 5*age - 161;
  const tdee = Math.round(bmr * act);
  document.getElementById("cal-tdee").textContent = tdee.toLocaleString() + " kcal";
  document.getElementById("cal-survival").textContent = Math.round(tdee * 0.5).toLocaleString() + " kcal";
  document.getElementById("cal-result").style.display = "block";
}

function calcRation() {
  const people = parseInt(document.getElementById("cal-people").value);
  const days = parseInt(document.getElementById("cal-days").value);
  const cpd = parseInt(document.getElementById("cal-cpd").value);
  const total = people * days * cpd;
  document.getElementById("ration-total").textContent = total.toLocaleString() + " kcal";
  const fmt = typeof fmtNum === "function" ? fmtNum : n => parseFloat(n.toFixed(2)).toLocaleString();
  const foods = [
    ["White rice", 3500], ["Dried pasta", 3580], ["Dried beans / lentils", 3400],
    ["Oats", 3890], ["Wheat flour", 3640], ["Cooking oil", 8840],
    ["Sugar", 3870], ["Dried milk powder", 5000], ["Canned tuna (100g)", 116]
  ];
  const foodsHtml = foods.map(([name, calPerKg]) => {
    const val = total / calPerKg;
    const unit = calPerKg < 500 ? Math.round(val).toLocaleString() + " cans" : fmt(val) + " kg";
    return '<div style="display:flex;justify-content:space-between;padding:5px 0;border-bottom:1px solid #eee;font-size:0.82rem;"><span>' + name + '</span><span style="font-weight:bold;">' + unit + '</span></div>';
  }).join("");
  document.getElementById("ration-foods").innerHTML =
    '<div style="font-size:0.72rem;color:#aaa;text-transform:uppercase;letter-spacing:0.04em;margin-bottom:6px;">Food equivalents</div>' + foodsHtml;
  document.getElementById("ration-result").style.display = "block";
}

function calcWindChill() {
  const T = parseFloat(document.getElementById("wc-temp").value);
  const V = parseFloat(document.getElementById("wc-wind").value);
  if (T > 10 || V < 4.8) {
    document.getElementById("wc-out").textContent = T.toFixed(1) + "C";
    document.getElementById("wc-risk").textContent = "Wind chill not applicable above 10C or below 4.8 km/h";
    document.getElementById("wc-result").style.display = "block";
    return;
  }
  const wc = 13.12 + 0.6215*T - 11.37*Math.pow(V,0.16) + 0.3965*T*Math.pow(V,0.16);
  let risk = "Low risk";
  if (wc < -10) risk = "Moderate - exposed skin at risk";
  if (wc < -28) risk = "High - frostbite in 10-30 min";
  if (wc < -40) risk = "Extreme - frostbite in under 2 min";
  document.getElementById("wc-out").textContent = wc.toFixed(1) + "C";
  document.getElementById("wc-risk").textContent = risk;
  document.getElementById("wc-result").style.display = "block";
}

function calcHeatIndex() {
  const T = parseFloat(document.getElementById("hi-temp").value);
  const R = parseFloat(document.getElementById("hi-hum").value);
  const Tf = T * 9/5 + 32;
  const HI_f = -42.379 + 2.04901523*Tf + 10.14333127*R
    - 0.22475541*Tf*R - 0.00683783*Tf*Tf - 0.05481717*R*R
    + 0.00122874*Tf*Tf*R + 0.00085282*Tf*R*R - 0.00000199*Tf*Tf*R*R;
  const hi = (HI_f - 32) * 5/9;
  let risk = "Low risk";
  if (hi >= 27) risk = "Caution - fatigue possible";
  if (hi >= 32) risk = "Extreme caution - heat cramps/exhaustion possible";
  if (hi >= 39) risk = "Danger - heat stroke likely";
  if (hi >= 46) risk = "Extreme danger - heat stroke imminent";
  document.getElementById("hi-out").textContent = hi.toFixed(1) + "C";
  document.getElementById("hi-risk").textContent = risk;
  document.getElementById("hi-result").style.display = "block";
}
